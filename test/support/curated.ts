// The curated tables, and the list of them — one declaration read by the row
// that pins them (C10 T2.39) and by the tool that re-takes the pin
// (`tools/curated/pin.ts`). Two copies of this list would be the drift the pin
// exists to prevent, one level out.
//
// **Why the values are pinned in a file rather than as digests in the row.** A
// digest is total — any different value fails, which is what *legal-but-
// different must fail* means — and it is opaque, so a failure says *something
// moved* and nothing about what. A table change that is legitimate then has to
// be reviewed by reading two revisions of the module side by side.
//
// Pinning the canonical **values** in `curated-pinned.json` is total in exactly
// the same way and reviewable as well: a deliberate change shows up as a diff of
// the entries, and a failing row prints the entries that moved rather than a new
// hash. The cost is a data file; the alternative was a hash plus a second copy
// of the values to diff against, which is the same file with a hash on top.
//
// **It is not a snapshot.** There is no `-u` and no write path from the test —
// re-taking the pin is `npx tsx tools/curated/pin.ts --write`, a deliberate act
// with a diff to read afterwards. A snapshot regenerated by a flag records what
// the code does; this records what was chosen.

/**
 * The one table whose *bulk* is reduced before pinning, with the reason — an
 * unstated reduction is a pin with a hole in it.
 *
 * `COLORMAPS` is 142 maps of 256 transcribed triples, and pinning every sample
 * by value is a 1.5 MB file for a table whose samples are **matplotlib's**, not
 * a choice made here. What *is* curated is which 142 maps ship, each one's
 * `kind`, and the reversed pairs — so those are pinned by value and the sample
 * array by a digest, which still names the map that moved. Every other table is
 * pinned whole.
 */
const REDUCE: Readonly<Record<string, (v: unknown) => unknown>> = {
  COLORMAPS: (v) => {
    const out: Record<string, unknown> = {};
    for (const [name, map] of Object.entries(v as Record<string, Record<string, unknown>>)) {
      out[name] = {
        kind: map["kind"],
        name: map["name"],
        data: `sha256:${createHash("sha256").update(JSON.stringify(map["data"])).digest("hex").slice(0, 16)}`,
      };
    }
    return out;
  },
};

/** The canonical form of every curated table, which is what `curated-pinned.json` holds. */
export const canonical = (): Record<string, unknown> => {
  const out: Record<string, unknown> = {};
  for (const name of Object.keys(CURATED).sort()) {
    const reduce = REDUCE[name];
    out[name] = canon(reduce === undefined ? CURATED[name] : reduce(CURATED[name]));
  }
  return out;
};

/**
 * The entries that differ between two canonical tables, as `path: was → now`.
 *
 * **This is the part the digest could not do.** A failing pin prints these, so a
 * legitimate change is read as a list of entries rather than as a hash nobody
 * can interpret — and an illegitimate one names the slot it touched.
 */
/**
 * A value short enough to read in a failure.
 *
 * **Measured rather than guessed at**: the first run of the differ printed 142
 * colormaps' full sample arrays — 456 KB of output for a change a reader wanted
 * one line about. A pin that cannot be read at the moment it fails is a digest
 * with extra steps.
 */
const show = (v: unknown): string => {
  if (v === undefined) return "(absent)";
  const text = JSON.stringify(v);
  return text.length <= 120 ? text : `${text.slice(0, 117)}…`;
};

export const entryDiff = (was: unknown, now: unknown, path = ""): readonly string[] => {
  const at = (k: string): string => (path === "" ? k : `${path}.${k}`);
  if (Array.isArray(was) && Array.isArray(now)) {
    const out: string[] = [];
    for (let i = 0; i < Math.max(was.length, now.length); i += 1) {
      out.push(...entryDiff(was[i], now[i], at(String(i))));
    }
    return out;
  }
  if (was !== null && now !== null && typeof was === "object" && typeof now === "object") {
    const keys = [...new Set([...Object.keys(was), ...Object.keys(now)])].sort();
    const out: string[] = [];
    for (const k of keys) {
      out.push(...entryDiff((was as Record<string, unknown>)[k], (now as Record<string, unknown>)[k], at(k)));
    }
    return out;
  }
  if (JSON.stringify(was) === JSON.stringify(now)) return [];
  return [`${path === "" ? "(the whole value)" : path}: ${show(was)} → ${show(now)}`];
};
